    /// The two shipped records have to agree, and the smaller one has to
    /// be smaller: a compiled closure the size of the lockfile closure
    /// would mean the narrowing silently did nothing.
    #[test]
    fn the_shipped_closure_is_backed_by_the_shipped_lockfile_and_narrower() {
        let text = std::fs::read_to_string(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(JUDGED_CLOSURE_RELATIVE),
        )
        .unwrap();
        let packages =
            parse_lock(&std::fs::read_to_string(workspace_root().join("Cargo.lock")).unwrap());
        let reachable = closure(&packages, super::CLOSURE_ROOT);
        // The record is generated, so this reads its entries without a
        // JSON dependency the shared module does not have.
        let mut entries = Vec::new();
        let mut name: Option<String> = None;
        for line in text.lines().map(str::trim) {
            if let Some(value) = line.strip_prefix("\"name\": \"") {
                name = value.strip_suffix("\",").map(str::to_owned);
            } else if let Some(value) = line.strip_prefix("\"version\": \"") {
                let version = value.trim_end_matches('"').trim_end_matches("\",");
                if let Some(name) = name.take() {
                    entries.push((name, version.to_owned()));
                }
            }
        }
        assert!(!entries.is_empty());
        assert!(
            entries.len() < reachable.len(),
            "{} compiled vs {} reachable",
            entries.len(),
            reachable.len()
        );
        for (name, version) in &entries {
            assert!(
                reachable
                    .iter()
                    .any(|package| &package.name == name && &package.version == version),
                "{name} {version} is not in the judged lockfile"
            );
        }
    }
