"""Data shipped with the routing package: the support registry and the
chunked admission table.

``support_registry.v1.json`` is a byte-identical installed copy of the
machine-generated certification registry (``tables/support_registry.json``
in the repository); ``tools/generate_registry.py --check`` verifies the
two copies stay identical, so hand edits and drift are rejected the same
way they are for the repository copy.

``chunked_admission.v1.json`` is the admission table of the chunk-parallel
path (``toktier.chunked``): the certified artifacts whose chunked path
has recorded evidence, and for which paths. It is generated by
``tools/update_chunked_admission.py`` from the campaign readings and
checked by the same tool's ``--check``; the module verifies its root
digest when it loads it.

The files live inside the package, not only next to the repository's
generated tables, because an installed wheel has to be able to report
certification statuses -- the per-delivery, per-architecture status maps
``explain()`` and the explicit GPU engine's reports carry -- and to decide
chunked admission without a source checkout.
"""

from __future__ import annotations

from pathlib import Path

__all__ = ["CHUNKED_ADMISSION", "SUPPORT_REGISTRY", "TABLE_DIR"]

#: Directory of the shipped data files.
TABLE_DIR = Path(__file__).resolve().parent

#: The support registry shipped with the package.
SUPPORT_REGISTRY = TABLE_DIR / "support_registry.v1.json"

#: The chunk-parallel admission table shipped with the package.
CHUNKED_ADMISSION = TABLE_DIR / "chunked_admission.v1.json"
